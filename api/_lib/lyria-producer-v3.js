function lyriaProducerV3EnvEnabled() {
  const v = String(process.env.LYRIA_PRODUCER_V3 || "").trim().toLowerCase();
  if (v === "1" || v === "true" || v === "yes" || v === "on") return true;
  if (v === "0" || v === "false" || v === "no" || v === "off") return false;
  return true;
}

function flagOff(raw) {
  return raw === "0" || raw === 0 || raw === false || raw === "false";
}
function flagOn(raw) {
  return raw === "1" || raw === 1 || raw === true || raw === "true";
}

/** Admin-only. Settings Gemini-producer Off disables v3. Non-admins stay on bare Lyria. */
function resolveLyriaProducerV3Enabled(body, isAdmin = false) {
  if (!isAdmin) return false;
  if (!lyriaProducerV3EnvEnabled()) return false;
  if (flagOff(body?.lyriaProducerV3)) return false;
  if (flagOn(body?.lyriaProducerV3)) return true;
  if (flagOff(body?.geminiProducer)) return false;
  if (flagOn(body?.geminiProducer)) return true;
  return true;
}

function extractBpmFromText(text) {
  const m = String(text || "").match(/\b(\d{2,3})\s*bpm\b/i);
  if (!m) return 0;
  const n = Number(m[1]);
  if (!Number.isFinite(n) || n < 50 || n > 220) return 0;
  return n;
}

function extractMeterFromText(text) {
  const s = String(text || "").toLowerCase();
  if (/\b6\s*\/\s*8\b/.test(s) || /\b6-8\b/.test(s)) return "6/8";
  if (/\b3\s*\/\s*4\b/.test(s)) return "3/4";
  if (/\b2\s*\/\s*4\b/.test(s)) return "2/4";
  if (/\b4\s*\/\s*4\b/.test(s)) return "4/4";
  return "";
}

function styleFamilyId(style = "") {
  const s = String(style || "").toLowerCase();
  if (/\bdabke|dabkeh|ktakufti\b/.test(s)) return "dabke";
  if (/\bkhaleeji|khaliji|gulf|ardah|samri\b/.test(s)) return "khaleeji";
  if (/\bballad|tarab|mawwal|slow\b/.test(s) && !/\bpop\b/.test(s)) return "ballad";
  return "pop";
}

function defaultBpmForStyleFamily(style = "") {
  switch (styleFamilyId(style)) {
    case "dabke":
      return 126;
    case "khaleeji":
      return 95;
    case "ballad":
      return 80;
    default:
      return 105;
  }
}

function resolveV3Bpm(style = "", explicit) {
  const n = Number(explicit);
  if (Number.isFinite(n) && n >= 50 && n <= 220) return Math.round(n);
  return extractBpmFromText(style) || defaultBpmForStyleFamily(style);
}

function resolveV3Meter(style = "", explicit) {
  const raw = String(explicit || "").trim();
  if (raw === "6/8" || raw === "4/4" || raw === "3/4" || raw === "2/4") return raw;
  return extractMeterFromText(style) || "4/4";
}

function secondsPerBar(bpm, meter) {
  const b = Math.max(50, Number(bpm) || 105);
  if (String(meter) === "6/8") return 120 / b;
  if (String(meter) === "3/4") return 180 / b;
  if (String(meter) === "2/4") return 120 / b;
  return 240 / b;
}

function styleAlreadyDescribesVocal(style = "") {
  return /\b(male|female|lead vocal|vocals?|singer|tenor|alto|baritone|soprano|chant)\b/i.test(
    String(style || ""),
  );
}

function impliedInstrumentsForStyle(style = "") {
  const id = styleFamilyId(style);
  if (id === "dabke") return ["mijwiz", "darbuka"];
  if (id === "khaleeji") return ["oud", "mirwas", "claps"];
  if (id === "ballad") {
    if (/\btarab|mawwal|folk\b/i.test(style)) return ["oud", "nay", "riqq", "violins"];
    return ["piano", "strings", "oud"];
  }
  return ["keys", "drums", "bass"];
}

function instrumentsInText(text = "") {
  const s = String(text || "").toLowerCase();
  return INSTRUMENT_WORDS.filter((w) => new RegExp(`\\b${w}s?\\b`, "i").test(s));
}

function allowedInstruments(style = "") {
  const named = instrumentsInText(style);
  if (named.length) return named;
  return impliedInstrumentsForStyle(style);
}

function fmtTime(sec) {
  const t = Math.max(0, Math.round(Number(sec) || 0));
  const m = Math.floor(t / 60);
  const s = t % 60;
  return `${m}:${String(s).padStart(2, "0")}`;
}

function capWords(text, max) {
  const parts = String(text || "").trim().split(/\s+/).filter(Boolean);
  return parts.slice(0, max).join(" ");
}

function cleanLyricLine(line) {
  let t = stripInlinePunctuationFromSungLine(String(line || ""));
  t = t.replace(/[-–—]/g, " ").replace(/["«»]/g, "").replace(/\s+/g, " ").trim();
  return t;
}

function normalizeSectionName(name) {
  const raw = String(name || "").trim();
  if (!raw) return "";
  return SECTION_NAME_MAP[raw.toLowerCase()] || raw.replace(/\s+/g, " ");
}

function isChorusName(name) {
  return name === "Chorus" || name === "Final Chorus";
}

function styleMentionsMawwal(style = "") {
  return /\bmawwal\b/i.test(String(style || ""));
}

function lyricsTokens(text) {
  return String(text || "")
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g, "")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim()
    .split(/\s+/)
    .filter(Boolean);
}

function tokensInOrder(source, found) {
  const a = lyricsTokens(source);
  const b = lyricsTokens(found);
  if (!a.length) return true;
  let i = 0;
  for (const tok of b) {
    if (tok === a[i]) i += 1;
    if (i >= a.length) return true;
  }
  return i >= a.length;
}

function dialectSentence(body = {}, style = "") {
  const styleText = String(style || "");
  if (/\bcolloquial (arabic )?vocal\b/i.test(styleText) && /sung to a /i.test(styleText)) {
    return "";
  }
  const label = resolveLyriaDialectLabel(body);
  let dialectBit = "";
  if (label) {
    dialectBit = /modern standard|msa/i.test(label)
      ? "Modern Standard Arabic vocal"
      : `${label} colloquial Arabic vocal`;
  } else if (String(body?.dialectHint || body?.dialect || "").trim()) {
    dialectBit = "colloquial Arabic vocal";
  }
  const addr = String(resolveLyriaArabicAddress(body) || "").trim().toLowerCase();
  let to = "";
  if (addr === "female") to = "sung to a woman";
  else if (addr === "male") to = "sung to a man";
  else if (addr === "group") to = "sung to a group";
  const parts = [dialectBit, to].filter(Boolean);
  if (!parts.length) return "";
  const sentence = `${parts.join(", ")}.`;
  if (styleText.toLowerCase().includes(sentence.slice(0, 24).toLowerCase())) return "";
  return sentence;
}

function composeV3StyleLine(body = {}, { bpmAppended } = {}) {
  let style = String(body?.style || "").trim();
  const vocal = String(body?.vocalGender || "").trim().toLowerCase();
  if (!styleAlreadyDescribesVocal(style)) {
    if (vocal === "m" && !/\bmale lead vocal\b/i.test(style)) {
      style = style ? `${style}, male lead vocal` : "male lead vocal";
    } else if (vocal === "f" && !/\bfemale lead vocal\b/i.test(style)) {
      style = style ? `${style}, female lead vocal` : "female lead vocal";
    }
  }
  if (bpmAppended && bpmAppended > 0 && !extractBpmFromText(style)) {
    style = style ? `${style}, ${bpmAppended} BPM` : `${bpmAppended} BPM`;
  }
  return style;
}

function compactPreviousTake(raw) {
  const src = raw && typeof raw === "object" ? raw : {};
  const list = Array.isArray(src.sections) ? src.sections : Array.isArray(raw) ? raw : [];
  const sections = list.map((s) => ({
    name: String(s?.name || "").trim(),
    bars: Number.isFinite(Number(s?.bars)) ? Math.round(Number(s.bars)) : 0,
    arrangement: String(s?.arrangement || "").trim(),
    intensity: Number.isFinite(Number(s?.intensity)) ? Math.round(Number(s.intensity)) : 0,
    lyrics: Array.isArray(s?.lyrics) ? s.lyrics.map((line) => String(line || "").trim()).filter(Boolean) : [],
    backing: Array.isArray(s?.backing) ? s.backing.map((line) => String(line || "").trim()).filter(Boolean) : [],
  })).filter((s) => s.name);
  return sections.length ? { sections } : null;
}

function buildLyriaProducerV3Input(body = {}, { lyrics = "", durationSec = 0 } = {}) {
  const idea = isLyriaIdeaPromptBody(body);
  const rawPrompt = String(lyrics || body?.prompt || "").trim();
  const ideaBrief = String(body?.ideaBrief || (idea ? rawPrompt : "")).trim();
  const style = String(body?.style || "").trim();
  const bpm = resolveV3Bpm(style, body?.bpm || body?.tempo);
  const timeSignature = resolveV3Meter(style, body?.timeSignature);
  const maxSec = 180;
  const cap = Number(durationSec) > 0
    ? Math.max(60, Math.min(maxSec, Math.round(durationSec)))
    : maxSec;
  const previousTake = compactPreviousTake(body?.previousTake || body?.previous_take);
  return {
    title: String(body?.title || "").trim(),
    lyrics_raw: idea ? "" : rawPrompt,
    idea_brief: idea ? ideaBrief : "",
    style_tags: style,
    instruments: String(body?.instruments || "").trim(),
    song_key: String(body?.songKey || "").trim(),
    bpm,
    timeSignature,
    vocal_gender: String(body?.vocalGender || "").trim(),
    dialect_hint: String(body?.dialectHint || body?.dialect || "").trim(),
    arabic_address: String(body?.arabicAddress || body?.address || "").trim().toLowerCase(),
    instrumental: Boolean(body?.instrumental),
    script_format: String(body?.scriptFormat || "").trim(),
    target: "full_length_song",
    max_length_seconds: cap,
    target_length_seconds: cap,
    length_note: "max_not_target_shorter_ok",
    flow: "lyria_producer_v3",
    ...(previousTake ? { previous_take: previousTake } : {}),
  };
}

function normalizeLyriaProducerV3Output(raw, { instrumental = false, input = {} } = {}) {
  if (!raw || typeof raw !== "object") return null;
  const list = Array.isArray(raw.sections) ? raw.sections : [];
  if (!list.length) return null;
  const style = String(input?.style_tags || "").trim();
  const mawwal = styleMentionsMawwal(style);
  const sections = [];
  for (const item of list) {
    const name = normalizeSectionName(item?.name);
    if (!name) continue;
    let bars = Math.max(0, Math.round(Number(item?.bars) || 0));
    if (name === "Mawwal") bars = 0;
    if (name === "Intro" && bars < 8) bars = 8;
    if (name !== "Mawwal" && name !== "Intro" && bars < 2) {
      bars = name === "Outro" || name === "Bridge" || name === "Instrumental" ? 4 : 8;
    }
    let arrangement = capWords(String(item?.arrangement || "").trim(), 16);
    if (name === "Mawwal" && !arrangement) arrangement = capWords("solo oud, free-time", 16);
    if (!arrangement) continue;
    let intensity = Math.round(Number(item?.intensity) || 0);
    if (!Number.isFinite(intensity) || intensity < 1) intensity = 4;
    intensity = Math.max(1, Math.min(10, intensity));
    const lyrics = instrumental
      ? []
      : (Array.isArray(item?.lyrics) ? item.lyrics : [])
        .map(cleanLyricLine)
        .filter(Boolean)
        .slice(0, 16);
    const backing = instrumental || !isChorusName(name)
      ? []
      : (Array.isArray(item?.backing) ? item.backing : [])
        .map(cleanLyricLine)
        .filter(Boolean)
        .slice(0, 2);
    sections.push({
      name,
      bars,
      arrangement,
      intensity,
      lyrics: name === "Intro" || name === "Outro" || name === "Instrumental" ? [] : lyrics,
      backing,
    });
  }
  if (!sections.length) return null;

  const first = sections[0];
  if (!/^(Intro|Mawwal)$/.test(first.name)) {
    sections.unshift(
      mawwal
        ? {
            name: "Mawwal",
            bars: 0,
            arrangement: capWords("solo oud, free-time", 16),
            intensity: 3,
            lyrics: [],
            backing: [],
          }
        : {
            name: "Intro",
            bars: 8,
            arrangement: capWords("soft, 1-2 instruments", 16),
            intensity: 2,
            lyrics: [],
            backing: [],
          },
    );
  } else if (mawwal && first.name === "Intro") {
    first.name = "Mawwal";
    first.bars = 0;
  }

  const chorus = sections.find((s) => s.name === "Chorus" && s.lyrics.length);
  if (chorus) {
    for (const s of sections) {
      if (s.name === "Final Chorus" || s.name === "Chorus") {
        s.lyrics = [...chorus.lyrics];
      }
    }
  }

  return { sections, v3: true };
}

function assignTimestamps(sections, { bpm, meter }) {
  const spb = secondsPerBar(bpm, meter);
  const out = sections.map((s) => ({ ...s, lyrics: [...(s.lyrics || [])], backing: [...(s.backing || [])] }));
  const durationOf = (s) => {
    if (s.name === "Mawwal") {
      return Math.max(MAWWAL_SECONDS_MIN, Math.min(MAWWAL_SECONDS_MAX, MAWWAL_SECONDS));
    }
    const bars = Math.max(1, Number(s.bars) || 4);
    return Math.max(2, bars * spb);
  };
  const stamp = (list) => {
    let t = 0;
    for (const s of list) {
      const dur = Math.max(1, Math.round(durationOf(s)));
      s.startSec = t;
      s.endSec = t + dur;
      t = s.endSec;
    }
    return t;
  };
  let total = stamp(out);
  if (total > 180) {
    for (const s of out) {
      if ((s.name === "Verse 1" || s.name === "Verse 2" || isChorusName(s.name)) && s.bars >= 16) {
        s.bars = 8;
      }
    }
    total = stamp(out);
  }
  if (total > 180) {
    const scale = 180 / total;
    let t = 0;
    for (const s of out) {
      const dur = Math.max(1, Math.round((s.endSec - s.startSec) * scale));
      s.startSec = t;
      s.endSec = t + dur;
      t = s.endSec;
    }
  }
  return out;
}

function displayLyricsFromSections(sections, { instrumental = false } = {}) {
  if (instrumental) return "";
  const blocks = [];
  for (const s of sections) {
    if (!s.lyrics?.length) continue;
    const lines = [...s.lyrics];
    if (isChorusName(s.name) && s.backing?.length) {
      const last = lines.length - 1;
      if (last >= 0) lines[last] = `${lines[last]} (${s.backing[0]})`;
    }
    blocks.push(`[${s.name}]\n${lines.join("\n")}`);
  }
  return blocks.join("\n\n").trim();
}

function arrangementUsesOnlyAllowed(arrangement, allowed) {
  const used = instrumentsInText(arrangement);
  if (!used.length || !allowed.length) return true;
  return used.every((u) =>
    allowed.some((a) => a === u || a.startsWith(u) || u.startsWith(a) || `${a}s` === u || `${u}s` === a),
  );
}

function validateLyriaPromptV3({
  prompt,
  styleLine,
  sections,
  lyricsRaw = "",
  ideaMode = false,
  instrumental = false,
} = {}) {
  const text = String(prompt || "");
  if (!text) return { ok: false, error: "empty_prompt" };
  if (!text.startsWith(String(styleLine || "").trim())) {
    return { ok: false, error: "style_not_verbatim_prefix" };
  }
  if (/\bIntensity\s+\d+\s*\/\s*10\b/i.test(text)) {
    return { ok: false, error: "intensity_leaked" };
  }
  const chorusLines = [];
  for (const s of sections || []) {
    if (FORBIDDEN_ARRANGEMENT.test(s.arrangement || "")) {
      return { ok: false, error: `forbidden_arrangement:${s.name}` };
    }
    if (isChorusName(s.name) && s.lyrics?.length) {
      chorusLines.push(s.lyrics.join("\n"));
    }
  }
  if (chorusLines.length >= 2) {
    const first = chorusLines[0];
    if (chorusLines.some((c) => c !== first)) {
      return { ok: false, error: "chorus_mismatch" };
    }
  }
  // write_lyrics_not_preserved is not enforced: Write lyrics may be adapted.
  return { ok: true };
}

/**
 * @returns {{ ok: true, prompt: string, styleLine: string, bpm: number, meter: string, sections: object[], displayLyrics: string, bpmAppended: number } | { ok: false, error: string }}
 */
function buildLyriaPromptV3({
  body = {},
  producerResult,
  instrumental = false,
  lyricsRaw = "",
} = {}) {
  const sectionsIn = producerResult?.sections;
  if (!Array.isArray(sectionsIn) || !sectionsIn.length) {
    return { ok: false, error: "no_sections" };
  }
  const styleOrig = String(body?.style || "").trim();
  const bpm = resolveV3Bpm(styleOrig, producerResult?.bpm || body?.bpm);
  const meter = resolveV3Meter(styleOrig, body?.timeSignature);
  const parsedBpm = extractBpmFromText(styleOrig);
  const bpmAppended = parsedBpm ? 0 : bpm;
  const styleLine = composeV3StyleLine(body, { bpmAppended });
  if (!styleLine) return { ok: false, error: "empty_style" };

  for (const s of sectionsIn) {
    if (FORBIDDEN_ARRANGEMENT.test(s.arrangement || "")) {
      return { ok: false, error: `forbidden_arrangement:${s.name}` };
    }
    // unknown_instrument is not enforced: genre-fitting extra instruments are allowed.
  }

  const timed = assignTimestamps(sectionsIn, { bpm, meter });
  const dialect = dialectSentence(body, styleLine);
  const arabizi = isArabiziScript({
    scriptFormat: String(body?.scriptFormat || "").trim(),
    lyrics: lyricsRaw,
  });
  const arabiziSentence = arabizi
    ? "Lyrics are Arabic written in Latin letters, sung with authentic Arabic pronunciation."
    : "";

  const head = [styleLine + "."];
  if (instrumental) head.push("Instrumental only.");
  if (dialect) head.push(dialect);
  if (arabiziSentence) head.push(arabiziSentence);

  const vocalEnter = "vocal enters on the downbeat after the intro phrase ends";
  const arrLines = timed.map((s) => {
    let a = String(s.arrangement || "").replace(/\.\s*$/, "");
    if (s.name === "Verse 1" && !/vocal enters on the downbeat/i.test(a)) {
      a = a ? `${a}; ${vocalEnter}` : vocalEnter;
    }
    return `[${fmtTime(s.startSec)} - ${fmtTime(s.endSec)}] ${s.name}: ${a}`;
  });

  const blocks = [head.join(" ").replace(/\.\s*\./g, ".").trim(), "", ...arrLines];

  if (!instrumental) {
    const lyricBlocks = [];
    for (const s of timed) {
      if (!s.lyrics?.length) continue;
      const lines = s.lyrics.map((line, i) => {
        if (isChorusName(s.name) && i === s.lyrics.length - 1 && s.backing?.[0]) {
          return `${line} (${s.backing[0]})`;
        }
        return line;
      });
      lyricBlocks.push(`[${s.name}]`, ...lines, "");
    }
    if (lyricBlocks.length) {
      blocks.push("", "Lyrics:", "", ...lyricBlocks);
    }
  }

  const prompt = blocks.join("\n").replace(/\n{3,}/g, "\n\n").trim().slice(0, MAX_PROMPT_CHARS);
  const ideaMode = isLyriaIdeaPromptBody(body);
  const check = validateLyriaPromptV3({
    prompt,
    styleLine,
    sections: timed,
    lyricsRaw,
    ideaMode,
    instrumental,
  });
  if (!check.ok) return { ok: false, error: check.error };

  return {
    ok: true,
    prompt,
    styleLine,
    bpm,
    meter,
    bpmAppended,
    sections: timed,
    displayLyrics: displayLyricsFromSections(timed, { instrumental }),
  };
}

function appendLyriaProducerV3AdminDetail(producerResult, stitch) {
  const applied = Boolean(producerResult?.ok) && !producerResult?.fallback && stitch?.ok !== false;
  const reason = String(
    producerResult?.error || stitch?.error || (!applied ? "plan_failed" : ""),
  ).trim();
  const lines = [`producer: ${applied ? "applied" : "error"}`];
  if (producerResult?.v3Attempts) lines.push(`lyria_producer_v3_attempts: ${producerResult.v3Attempts}`);
  if (!applied && reason) lines.push(`producer_reason: ${reason}`);
  if (producerResult?.model) lines.push(`lyria_producer_v3_model: ${producerResult.model}`);
  if (producerResult?.latencyMs != null) lines.push(`lyria_producer_v3_ms: ${producerResult.latencyMs}`);
  if (stitch?.bpm) lines.push(`lyria_producer_v3_bpm: ${stitch.bpm} ${stitch.meter || ""}`.trim());
  if (stitch?.bpmAppended) lines.push(`lyria_producer_v3_bpm_appended: ${stitch.bpmAppended}`);
  const secs = stitch?.sections || producerResult?.sections || [];
  if (secs.length) {
    lines.push(`lyria_producer_v3_sections: ${secs.map((s) => {
      if (s.name === "Mawwal") {
        const dur = Math.max(0, Math.round((Number(s.endSec) || 0) - (Number(s.startSec) || 0)))
          || MAWWAL_SECONDS;
        return `Mawwal:${dur}s`;
      }
      return `${s.name}:${s.bars || 0}`;
    }).join(",")}`);
  }
  return lines.join("\n");
}

